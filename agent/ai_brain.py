class DecisionType(Enum):
    """Types of trading decisions"""
    ENTER_LONG = "enter_long"
    ENTER_SHORT = "enter_short"
    EXIT_POSITION = "exit_position"
    HOLD_POSITION = "hold_position"
    ADJUST_STOP = "adjust_stop"
    SCALE_IN = "scale_in"
    SCALE_OUT = "scale_out"
    NO_ACTION = "no_action"


class ConfidenceLevel(Enum):
    """Confidence levels for decisions"""
    VERY_LOW = 1
    LOW = 2
    MODERATE = 3
    HIGH = 4
    VERY_HIGH = 5


@dataclass
class MarketContext:
    """Current market context for decision making"""
    
    symbol: str
    current_price: float
    timestamp: datetime = field(default_factory=datetime.now)
    
    # Price data
    prices: List[float] = field(default_factory=list)
    volumes: List[float] = field(default_factory=list)
    highs: List[float] = field(default_factory=list)
    lows: List[float] = field(default_factory=list)
    
    # Technical indicators
    indicators: Dict[str, float] = field(default_factory=dict)
    
    # Market state
    volatility: float = 0.0
    trend: str = "neutral"  # bullish, bearish, neutral
    momentum: str = "neutral"  # strong_up, up, neutral, down, strong_down
    
    # Sentiment
    sentiment_score: float = 0.5
    news_sentiment: float = 0.5
    social_sentiment: float = 0.5
    
    # Additional data
    market_cap: Optional[float] = None
    volume_24h: Optional[float] = None
    price_change_24h: Optional[float] = None
    
    def to_dict(self) -> Dict:
        return {
            "symbol": self.symbol,
            "current_price": self.current_price,
            "timestamp": self.timestamp.isoformat(),
            "trend": self.trend,
            "momentum": self.momentum,
            "volatility": round(self.volatility, 4),
            "sentiment": round(self.sentiment_score, 3),
        }


@dataclass
class TradeSignal:
    """A trading signal generated by the AI Brain"""
    
    symbol: str
    action: DecisionType
    confidence: float
    reasoning: str
    
    # Trade parameters
    suggested_entry: Optional[float] = None
    suggested_stop: Optional[float] = None
    suggested_target: Optional[float] = None
    position_size_percent: float = 2.0
    
    # Signal metadata
    signal_strength: float = 0.5
    risk_reward_ratio: float = 2.0
    expected_holding_time: str = "hours"  # minutes, hours, days, weeks
    
    # Factor breakdown
    factors: Dict[str, float] = field(default_factory=dict)
    
    # Related memories
    relevant_memories: List[str] = field(default_factory=list)
    
    # Timestamp
    created_at: datetime = field(default_factory=datetime.now)
    
    def to_dict(self) -> Dict:
        return {
            "symbol": self.symbol,
            "action": self.action.value,
            "confidence": round(self.confidence, 3),
            "reasoning": self.reasoning,
            "suggested_entry": self.suggested_entry,
            "suggested_stop": self.suggested_stop,
            "suggested_target": self.suggested_target,
            "position_size_percent": self.position_size_percent,
            "signal_strength": round(self.signal_strength, 3),
            "risk_reward_ratio": self.risk_reward_ratio,
            "factors": {k: round(v, 3) for k, v in self.factors.items()},
            "created_at": self.created_at.isoformat(),
        }


